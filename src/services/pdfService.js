const PDFDocument = require('pdfkit');

// Industrial styling colors
const COLORS = {
  headerBg: '#0F2A4A',      // Dark Navy
  accentTeal: '#0D9488',    // Industrial Teal
  textDark: '#0F172A',      // Slate 900
  textMuted: '#475569',     // Slate 600
  tableHeaderBg: '#1E293B', // Slate 800
  tableBorder: '#CBD5E1',   // Slate 300
  rowEven: '#FFFFFF',
  rowOdd: '#F8FAFC',
  activeGreen: '#16A34A',
  warningOrange: '#D97706',
  dangerRed: '#DC2626'
};

function drawHeader(doc, title, subtitle, user) {
  // Top Banner
  doc.rect(0, 0, doc.page.width, 50).fill(COLORS.headerBg);
  doc.rect(0, 50, doc.page.width, 4).fill(COLORS.accentTeal);

  doc.fillColor('#FFFFFF').fontSize(16).font('Helvetica-Bold')
     .text('SMART TROLLEY MAINTENANCE TRACKER', 35, 14, { align: 'left' });
  doc.fontSize(10).font('Helvetica')
     .fillColor('#94A3B8')
     .text('Plant Equipment Inspection & Audit System', 35, 33, { align: 'left' });

  doc.fontSize(9).fillColor('#FFFFFF')
     .text(`Date: ${new Date().toLocaleDateString('en-GB')}`, doc.page.width - 200, 16, { align: 'right', width: 165 })
     .text(`Generated By: ${user?.name || 'Administrator'}`, doc.page.width - 200, 30, { align: 'right', width: 165 });

  doc.moveDown(2);

  // Section Title
  const startY = 70;
  doc.fillColor(COLORS.textDark).fontSize(14).font('Helvetica-Bold').text(title, 35, startY);
  doc.fontSize(9).font('Helvetica').fillColor(COLORS.textMuted).text(subtitle, 35, startY + 18);
  doc.moveDown(1.5);
}

function drawFooter(doc) {
  const bottom = doc.page.height - 30;
  doc.rect(35, bottom - 10, doc.page.width - 70, 0.5).fill(COLORS.tableBorder);
  doc.fontSize(8).fillColor(COLORS.textMuted).font('Helvetica')
     .text('Official Plant Audit Record • ISO 9001 & IATF 16949 Compliant • Trolley Maintenance Tracker Cloud', 35, bottom, { align: 'left', width: 400 });
}

// 1. Trolleys Fleet Report PDF
function generateTrolleysPDF(trolleys, stream, user) {
  const doc = new PDFDocument({ margin: 35, size: 'A4', bufferPages: true });
  doc.pipe(stream);

  drawHeader(doc, 'Trolley Fleet Inventory & Status Report', 'Complete registry of car bumper carrier trolleys and operational statuses', user);

  // Summary Metrics Bar
  const total = trolleys.length;
  const active = trolleys.filter(t => t.status === 'ACTIVE').length;
  const underMaint = trolleys.filter(t => t.status === 'UNDER_MAINTENANCE' || t.status === 'MAINTENANCE').length;
  const retired = trolleys.filter(t => t.status === 'RETIRED').length;

  let y = 105;
  const cardW = (doc.page.width - 70 - 18) / 4;
  const kpis = [
    { label: 'TOTAL INVENTORY', val: total, color: COLORS.headerBg },
    { label: 'ACTIVE / READY', val: active, color: COLORS.activeGreen },
    { label: 'UNDER MAINT.', val: underMaint, color: COLORS.warningOrange },
    { label: 'RETIRED / SCRAP', val: retired, color: COLORS.dangerRed }
  ];

  kpis.forEach((k, idx) => {
    const x = 35 + idx * (cardW + 6);
    doc.roundedRect(x, y, cardW, 40, 4).fillAndStroke('#F1F5F9', COLORS.tableBorder);
    doc.fillColor(k.color).fontSize(14).font('Helvetica-Bold').text(String(k.val), x, y + 8, { width: cardW, align: 'center' });
    doc.fillColor(COLORS.textMuted).fontSize(7).font('Helvetica').text(k.label, x, y + 25, { width: cardW, align: 'center' });
  });

  y = 160;
  // Table Columns
  const cols = [
    { name: 'Trolley Code', width: 85, align: 'left' },
    { name: 'Plant Location / Zone', width: 140, align: 'left' },
    { name: 'Status', width: 95, align: 'center' },
    { name: 'Condition', width: 80, align: 'center' },
    { name: 'Notes / Specs', width: 125, align: 'left' }
  ];

  // Table Header
  doc.rect(35, y, doc.page.width - 70, 22).fill(COLORS.tableHeaderBg);
  let curX = 40;
  cols.forEach(col => {
    doc.fillColor('#FFFFFF').fontSize(8.5).font('Helvetica-Bold')
       .text(col.name, curX, y + 6, { width: col.width - 10, align: col.align });
    curX += col.width;
  });

  y += 22;

  // Table Rows
  trolleys.forEach((t, i) => {
    if (y > doc.page.height - 60) {
      doc.addPage();
      drawHeader(doc, 'Trolley Fleet Inventory (Continued)', 'Plant Asset Tracking', user);
      y = 110;
      doc.rect(35, y, doc.page.width - 70, 22).fill(COLORS.tableHeaderBg);
      curX = 40;
      cols.forEach(col => {
        doc.fillColor('#FFFFFF').fontSize(8.5).font('Helvetica-Bold')
           .text(col.name, curX, y + 6, { width: col.width - 10, align: col.align });
        curX += col.width;
      });
      y += 22;
    }

    const rowBg = i % 2 === 0 ? COLORS.rowEven : COLORS.rowOdd;
    doc.rect(35, y, doc.page.width - 70, 20).fillAndStroke(rowBg, COLORS.tableBorder);

    curX = 40;
    // Trolley Code
    doc.fillColor(COLORS.textDark).fontSize(8.5).font('Helvetica-Bold').text(t.trolley_code || 'N/A', curX, y + 5, { width: cols[0].width - 10, align: cols[0].align });
    curX += cols[0].width;

    // Location
    doc.fillColor(COLORS.textMuted).fontSize(8).font('Helvetica').text(t.location || 'Unassigned', curX, y + 5, { width: cols[1].width - 10, align: cols[1].align });
    curX += cols[1].width;

    // Status
    const statusCol = t.status === 'ACTIVE' ? COLORS.activeGreen : (t.status === 'UNDER_MAINTENANCE' ? COLORS.warningOrange : COLORS.dangerRed);
    doc.fillColor(statusCol).fontSize(8).font('Helvetica-Bold').text(t.status || 'UNKNOWN', curX, y + 5, { width: cols[2].width - 10, align: cols[2].align });
    curX += cols[2].width;

    // Condition
    doc.fillColor(COLORS.textDark).fontSize(8).font('Helvetica').text(t.condition || 'GOOD', curX, y + 5, { width: cols[3].width - 10, align: cols[3].align });
    curX += cols[3].width;

    // Notes
    doc.fillColor(COLORS.textMuted).fontSize(7.5).font('Helvetica').text((t.notes || '-').slice(0, 35), curX, y + 5, { width: cols[4].width - 10, align: cols[4].align });

    y += 20;
  });

  // Footer on all pages
  const totalPages = doc.bufferedPageRange().count;
  for (let i = 0; i < totalPages; i++) {
    doc.switchToPage(i);
    drawFooter(doc);
    doc.fontSize(8).fillColor(COLORS.textMuted).font('Helvetica')
       .text(`Page ${i + 1} of ${totalPages}`, doc.page.width - 100, doc.page.height - 30, { align: 'right', width: 65 });
  }

  doc.end();
}

